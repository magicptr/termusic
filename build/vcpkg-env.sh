#!/usr/bin/env bash
# Shared vcpkg bootstrap for build/make-release.sh and build/make-debug.sh.
#
#   . "$root/build/vcpkg-env.sh"
#   termusic_vcpkg_setup "$root"
#
# After a successful setup these are exported:
#
#   VCPKG_REAL_ROOT  the real, read-only vcpkg installation
#   VCPKG_OVERLAY    the checkout-local writable overlay (build/vcpkg-root)
#   VCPKG_TOOLCHAIN  <overlay>/scripts/buildsystems/vcpkg.cmake
#   VCPKG_INSTALLED  <overlay>/installed (where the manifest installs FTXUI)
#
# Why an overlay: vcpkg takes a lock on its own root during a reconfigure, and
# that root is not necessarily writable (a distro package, a shared checkout).
# build/vcpkg-root is a writable copy of the root's directory structure with
# `scripts`, `ports`, `triplets`, `versions` and the `vcpkg` executable
# symlinked, so the manifest install writes only inside this checkout.
#
# Discovery order, and nothing else:
#   1. $VCPKG_ROOT, when it names a valid vcpkg root;
#   2. `vcpkg` on PATH, resolved through symlinks to its real root;
#   3. a clear error. There is no fallback that could half-work.

termusic_vcpkg_die() {
  printf 'termusic build: %s\n' "$*" >&2
  exit 1
}

# A usable root has the executable AND the CMake toolchain the build points at.
termusic_vcpkg_is_root() { # candidate
  [ -n "${1:-}" ] && [ -x "$1/vcpkg" ] &&
    [ -f "$1/scripts/buildsystems/vcpkg.cmake" ]
}

# Prints the real vcpkg root, or returns non-zero.
termusic_vcpkg_find_root() {
  local candidate="${VCPKG_ROOT:-}"
  if [ -n "$candidate" ]; then
    if termusic_vcpkg_is_root "$candidate"; then
      printf '%s\n' "${candidate%/}"
      return 0
    fi
    printf 'termusic build: VCPKG_ROOT="%s" is not a vcpkg root ' "$candidate" >&2
    printf '(no vcpkg executable or scripts/buildsystems/vcpkg.cmake there)\n' >&2
  fi

  local executable
  executable="$(command -v vcpkg 2>/dev/null || true)"
  if [ -n "$executable" ]; then
    # `vcpkg` is often a symlink or a shim on PATH: follow it to the real file
    # and take its directory, which is the root.
    local resolved directory
    resolved="$(readlink -f "$executable" 2>/dev/null || printf '%s' "$executable")"
    directory="$(cd "$(dirname "$resolved")" 2>/dev/null && pwd)"
    if termusic_vcpkg_is_root "$directory"; then
      printf '%s\n' "$directory"
      return 0
    fi
    printf 'termusic build: %s is on PATH but %s is not a vcpkg root\n' \
      "$executable" "$directory" >&2
  fi
  return 1
}

# Discovers vcpkg and prepares the overlay. Sets the exported paths above.
termusic_vcpkg_setup() { # checkout root
  local root="$1"
  local real
  if ! real="$(termusic_vcpkg_find_root)"; then
    cat >&2 <<'MESSAGE'
termusic build requires vcpkg; install vcpkg or set VCPKG_ROOT.

  * FTXUI comes from the vcpkg manifest (vcpkg.json), so a build cannot start
    without vcpkg;
  * install it (https://github.com/microsoft/vcpkg#quick-start) and either put
    its `vcpkg` executable on PATH or export VCPKG_ROOT=/path/to/vcpkg;
  * libmpdclient and FFTW3F are NOT vcpkg packages: they are found through
    pkg-config and must be installed as system development packages.
MESSAGE
    exit 1
  fi

  local overlay="$root/build/vcpkg-root"
  mkdir -p "$overlay/buildtrees" "$overlay/downloads" "$overlay/packages" \
    "$overlay/installed" ||
    termusic_vcpkg_die "cannot create the writable overlay $overlay"

  local part
  for part in scripts ports triplets versions; do
    if [ ! -e "$overlay/$part" ]; then
      ln -s "$real/$part" "$overlay/$part" 2>/dev/null ||
        termusic_vcpkg_die "cannot link $real/$part into $overlay"
    fi
  done
  # Manifest mode runs the overlay's own vcpkg, so the overlay needs an entry
  # point. It is a one-line WRAPPER, not a symlink: recent vcpkg derives its
  # root from the executable's own location, and a symlink makes it announce a
  # root mismatch on every child invocation (`vcpkg fetch ...`) -- which lands
  # in the captured output and breaks tool discovery. The wrapper execs the real
  # binary with an explicit --vcpkg-root, so the overlay really is the root and
  # every write stays inside this checkout.
  if [ -L "$overlay/vcpkg" ]; then
    rm -f "$overlay/vcpkg"
  fi
  cat > "$overlay/vcpkg" <<WRAPPER
#!/bin/sh
# Generated by build/vcpkg-env.sh: run the real vcpkg with this overlay as its
# root, so ports, downloads and the installed tree all live in this checkout.
# The caller may already name a root (the CMake toolchain does), and vcpkg
# rejects the option twice, so it is only added when it is missing.
for arg in "\$@"; do
  case "\$arg" in
    --vcpkg-root|--vcpkg-root=*) exec '$real/vcpkg' "\$@" ;;
  esac
done
exec '$real/vcpkg' --vcpkg-root '$overlay' "\$@"
WRAPPER
  chmod +x "$overlay/vcpkg" ||
    termusic_vcpkg_die "cannot make $overlay/vcpkg executable"
  touch "$overlay/.vcpkg-root"

  if ! termusic_vcpkg_is_root "$overlay"; then
    termusic_vcpkg_die "the overlay $overlay is incomplete (vcpkg or the CMake toolchain is missing); remove it and build again"
  fi

  VCPKG_REAL_ROOT="$real"
  VCPKG_OVERLAY="$overlay"
  VCPKG_TOOLCHAIN="$overlay/scripts/buildsystems/vcpkg.cmake"
  VCPKG_INSTALLED="$overlay/installed"
  export VCPKG_REAL_ROOT VCPKG_OVERLAY VCPKG_TOOLCHAIN VCPKG_INSTALLED
}
